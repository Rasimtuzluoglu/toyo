-- Is emri kalem sablonlari: sik kullanilan iscilik ve parca aciklamalari.
CREATE TABLE work_order_item_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(20) NOT NULL,
    description VARCHAR(300) NOT NULL,
    default_quantity NUMERIC(12, 2) NOT NULL DEFAULT 1,
    default_unit_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT true,
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_wo_item_template_type CHECK (type IN ('HIZMET', 'PARCA')),
    CONSTRAINT ck_wo_item_template_quantity CHECK (default_quantity > 0),
    CONSTRAINT ck_wo_item_template_price CHECK (default_unit_price >= 0)
);

