-- Araç kabul formu, teslim tutanağı ve günlük randevular.

CREATE TABLE vehicle_intakes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id BIGINT NOT NULL UNIQUE REFERENCES work_orders (id) ON DELETE CASCADE,
    intake_at TIMESTAMP NOT NULL DEFAULT now(),
    fuel_level VARCHAR(20) NOT NULL,
    damage_notes VARCHAR(2000),
    valuables VARCHAR(500),
    created_by BIGINT REFERENCES users (id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP,
    CONSTRAINT ck_vehicle_intake_fuel CHECK (fuel_level IN ('BOS', 'CEYREK', 'YARIM', 'UCDORT', 'DOLU'))
);

CREATE TABLE vehicle_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_order_id BIGINT NOT NULL UNIQUE REFERENCES work_orders (id) ON DELETE CASCADE,
    delivered_at TIMESTAMP NOT NULL DEFAULT now(),
    receiver_name VARCHAR(200) NOT NULL,
    mileage INTEGER,
    fuel_level VARCHAR(20) NOT NULL,
    notes VARCHAR(2000),
    created_by BIGINT REFERENCES users (id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP,
    CONSTRAINT ck_vehicle_delivery_fuel CHECK (fuel_level IN ('BOS', 'CEYREK', 'YARIM', 'UCDORT', 'DOLU')),
    CONSTRAINT ck_vehicle_delivery_mileage CHECK (mileage IS NULL OR mileage >= 0)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers (id),
    vehicle_id BIGINT REFERENCES vehicles (id),
    starts_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANLANDI',
    notes VARCHAR(1000),
    created_by BIGINT REFERENCES users (id),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP,
    CONSTRAINT ck_appointments_status CHECK (status IN ('PLANLANDI', 'GELDI', 'IPTAL'))
);

CREATE INDEX idx_appointments_starts_at ON appointments (starts_at);
CREATE INDEX idx_appointments_customer ON appointments (customer_id);
